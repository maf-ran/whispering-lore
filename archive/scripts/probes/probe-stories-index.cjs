/* eslint-env node */
const { chromium } = require('playwright')

;(async () => {
  const base = 'http://127.0.0.1:' + (process.env.PORT || 3000)
  const browser = await chromium.launch()
  const page = await browser.newPage()
  const requests = []
  page.on('request', (r) => requests.push(r.url()))
  page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE ERROR:', m.text()) })
  await page.goto(base + '/stories.html')
  await page.waitForSelector('.story-card', { timeout: 15000 })
  await page.waitForTimeout(1000)
  const cardCount = await page.$$eval('.story-card', (els) => els.length)
  const shardHits = requests.filter((u) => u.includes('/data/sharded/stories/by-region/'))
  const idxHits = requests.filter((u) => u.includes('/data/sharded/stories/index.json'))
  console.log('story cards:', cardCount)
  console.log('stories shard requests:', shardHits.length)
  console.log('stories index requests:', idxHits.length)
  if (!cardCount) throw new Error('no story cards rendered')
  if (shardHits.length) throw new Error('unexpected stories shard loads: ' + shardHits.length)
  if (!idxHits.length) throw new Error('stories/index.json not fetched')
  await page.click('.story-card .card-cta')
  await page.waitForSelector('#story-detail:not(.is-hidden)', { timeout: 15000 })
  await page.waitForTimeout(1500)
  const title = await page.$eval('#detail-title', (el) => el.textContent)
  console.log('detail title:', title)
  if (!title) throw new Error('detail title empty')
  await browser.close()
  console.log('OK')
})().catch((e) => { console.error('PROBE FAIL', e); process.exit(1) })