/* eslint-env node */
const fs = require('fs')
const path = require('path')

describe('Static files', () => {
  const root = path.resolve(__dirname, '..')
  const files = ['index.html', 'about.html', 'bestiary.html', 'items.html', 'stories.html', 'world.html', 'quiz.html', 'mylore.html', 'methodology.html']
  const sitemapExcluded = ['404.html'];

  [...files, ...sitemapExcluded].forEach(f => {
    it(`${f} exists and has basic structure`, () => {
      const content = fs.readFileSync(path.join(root, f), 'utf-8')
      expect(content).toMatch(/<!DOCTYPE html>/i)
      expect(content).toMatch(/<html lang="en">/)
      expect(content).toMatch(/<title>/)
      expect(content).toMatch(/<link rel="stylesheet" href="css\/styles.css"/)
    })
  })

  it('robots.txt exists', () => {
    expect(fs.existsSync(path.join(root, 'robots.txt'))).toBe(true)
  })

  it('favicon.svg exists', () => {
    expect(fs.existsSync(path.join(root, 'favicon.svg'))).toBe(true)
  })
})

// sitemap.xml is generated by archive/scripts/seo-build.py at deploy time and is
// gitignored, so it cannot be read from a clean checkout. Assert the invariant
// instead: every page the generator lists must exist on disk, and every public
// page on disk must be listed. This is what would have caught blog.html, which
// seo-build.py hardcoded into the URL list while the file was untracked and
// therefore absent from the deploy.
describe('Sitemap URL list', () => {
  const root = path.resolve(__dirname, '..')
  const generator = fs.readFileSync(path.join(root, 'archive/scripts/seo-build.py'), 'utf-8')

  const urlsBlock = generator.match(/urls = \[([\s\S]*?)\n\s*\]/)
  expect(urlsBlock).not.toBeNull()

  const listed = [...urlsBlock[1].matchAll(/\(\s*'([^']*)'/g)]
    .map(m => (m[1] === '' ? 'index.html' : m[1]))
    .filter(Boolean)

  it('the generator declares a non-empty URL list', () => {
    expect(listed.length).toBeGreaterThan(0)
  })

  it('every listed page exists on disk', () => {
    const missing = listed.filter(p => !fs.existsSync(path.join(root, p)))
    expect(missing).toEqual([])
  })

  it('every public page on disk is listed', () => {
    const onDisk = fs
      .readdirSync(root)
      .filter(f => f.endsWith('.html') && f !== '404.html')
    const unlisted = onDisk.filter(f => !listed.includes(f))
    expect(unlisted).toEqual([])
  })

  it('does not list 404.html', () => {
    expect(listed).not.toContain('404.html')
  })
})
